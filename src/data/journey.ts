function steps(inputs: StepInput[]): JourneyStep[] {
  return inputs.map(
    ([id, title, uiType, choices, framing, questions, warning], index) => {
      // A visual world does not determine the participant's emotional meaning.
      const options = choices.length ? answers(choices) : undefined;
      const hypotheses = choices.length
        ? answers(
            choices.map(
              (_, choiceIndex) =>
                coachHypotheses[id]?.[choiceIndex] ??
                "טרם נוסחה משמעות אישית מספקת. יש להבחין בין החוויה, הפירוש והתגובה לפני הצעת הסבר למנגנון.",
            ),
          )
        : undefined;
      return {
        id,
        order: index + 1,
        traineeTitle: title,
        youthTraineeTitle: title,
        uiType,
        options,
        youthOptions: options ? answers(choices) : undefined,
        patternRevealed: hypotheses,
        youthPatternRevealed: hypotheses,
        coachFraming: framing,
        coachDeepeningQuestions: questions,
        coachWarning:
          warning ??
          "אפשר לא לדעת, לשנות תשובה, לעצור או לא להעמיק. בדוק שהמשמעות היא של המשתתף.",
      };
    },
  );
}

