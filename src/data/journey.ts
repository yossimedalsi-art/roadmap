export type WorldAnswers = {
  clouds: string[];
  forest: string[];
  arcade: string[];
  fairies: string[];
};
export type JourneyStep = {
  id: string;
  order: number;
  traineeTitle: string;
  youthTraineeTitle?: string;
  uiType:
    | "text-input"
    | "archetype-selector"
    | "structured-dialogue"
    | "reward"
    | "good-powers"
    | "meditation";
  options?: WorldAnswers;
  youthOptions?: WorldAnswers;
  patternRevealed?: WorldAnswers;
  youthPatternRevealed?: WorldAnswers;
  coachFraming?: string;
  coachDeepeningQuestions?: string[];
  coachWarning?: string;
};

const worlds = ["clouds", "forest", "arcade", "fairies"] as const;
function answers(values: string[]): WorldAnswers {
  return Object.fromEntries(
    worlds.map((world) => [world, [...values]]),
  ) as WorldAnswers;
}
type StepInput = [
  string,
  string,
  JourneyStep["uiType"],
  string[],
  string,
  string[],
  string?,
];
function steps(inputs: StepInput[]): JourneyStep[] {
  return inputs.map(
    ([id, title, uiType, choices, framing, questions, warning], index) => {
      // A visual world does not determine the participant's emotional meaning.
      const options = choices.length ? answers(choices) : undefined;
      const hypotheses = choices.length
        ? answers(
            choices.map(
              (choice) =>
                `כיוון לבדיקה בלבד בעקבות ״${choice}״: ${questions[0]} אין להסיק מכאן אבחנה או סיפור עבר.`,
            ),
          )
        : undefined;
      return {
        id,
        order: index + 1,
        traineeTitle: title,
        youthTraineeTitle: title,
        uiType,
        options,
        youthOptions: options ? answers(choices) : undefined,
        patternRevealed: hypotheses,
        youthPatternRevealed: hypotheses,
        coachFraming: framing,
        coachDeepeningQuestions: questions,
        coachWarning:
          warning ??
          "אפשר לא לדעת, לשנות תשובה, לעצור או לא להעמיק. בדוק שהמשמעות היא של המשתתף.",
      };
    },
  );
}

