function normalize(value: string): string {
  return value
    .normalize("NFKC")
    .replace(/[\u0591-\u05C7]/g, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLocaleLowerCase("he");
}
export function searchMechanisms(query: string): Mechanism[] {
  const normalized = normalize(query);
  if (!normalized) return mechanisms;
  const terms = normalized.split(" ");
  return mechanisms
    .map((mechanism) => {
      const primary = normalize(
        [mechanism.title, ...mechanism.aliases].join(" "),
      );
      const all = normalize(
        [
          primary,
          mechanism.domain,
          mechanism.emotionGroup,
          mechanism.openingQuestion,
          ...mechanism.scenarios.map((event) => event.title),
        ].join(" "),
      );
      return {
        mechanism,
        matches: terms.every((term) => all.includes(term)),
        score: primary.includes(normalized)
          ? 2
          : terms.filter((term) => primary.includes(term)).length /
            terms.length,
      };
    })
    .filter((result) => result.matches)
    .sort((a, b) => b.score - a.score)
    .map((result) => result.mechanism);
}
